/**
 * The corpus manifest (#351): `src/features/texts/corpus/manifest.ts` imports every content file under
 * `src/features/texts/corpus/content/{fr,en}/*.json`, so the bundler ships them and the generator stays
 * pure (no file system at runtime). Curators (#342) add a JSON file and run this; no code to edit.
 *
 *   npm run corpus            rewrite the manifest
 *   npm run corpus -- --check exit 1 when the committed manifest does not list the files on disk
 *
 * `src/features/texts/corpus/content.test.ts` runs the same check. The manifest also carries a content
 * version per language (#342 C7): a hash of that language's file names and bytes, so the file provider's
 * `sourceRef` changes whenever the corpus does.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

export const CONTENT_DIR = "src/features/texts/corpus/content";
export const MANIFEST = "src/features/texts/corpus/manifest.ts";
const LANGUAGES = ["en", "fr"] as const;

/** The content files on disk, `<language>/<file>.json`, sorted. */
export function contentFiles(root = "."): string[] {
  return LANGUAGES.flatMap((language) => {
    const dir = path.join(root, CONTENT_DIR, language);
    if (!fs.existsSync(dir)) return [];
    return fs
      .readdirSync(dir)
      .filter((f) => f.endsWith(".json"))
      .sort()
      .map((f) => `${language}/${f}`);
  });
}

/** A short, stable hash of one language's content files (names and bytes, in order). */
export function contentVersion(
  language: string,
  files: readonly string[],
  read: (file: string) => string | Buffer = (f) => fs.readFileSync(path.join(CONTENT_DIR, f)),
): string {
  const hash = createHash("sha256");
  for (const f of files.filter((name) => name.startsWith(`${language}/`))) {
    hash.update(`${f}\0`);
    hash.update(read(f));
    hash.update("\0");
  }
  return hash.digest("hex").slice(0, 12);
}

/** The manifest's source for `files`. */
export function manifestSource(
  files: readonly string[],
  version: (language: string) => string = (language) => contentVersion(language, files),
): string {
  const name = (i: number) => `f${i}`;
  const imports = files.map((f, i) => `import ${name(i)} from "./content/${f}";`).join("\n");
  const entries = files.map((f, i) => `  ["${f}", ${name(i)}],`).join("\n");
  return `// Generated by scripts/corpus-manifest.ts (npm run corpus). Do not edit by hand.
${imports}

/** Every content file, \`<language>/<file>.json\` -> its raw JSON (parsed by \`files.ts\`). */
export const CONTENT_FILES: ReadonlyArray<readonly [string, unknown]> = [
${entries}
];

/** Per language, a hash of its content files: changes whenever a file is added, removed or edited. */
export const CONTENT_VERSION = {
${LANGUAGES.map((language) => `  ${language}: "${version(language)}",`).join("\n")}
} as const;
`;
}

function main() {
  const source = manifestSource(contentFiles());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(MANIFEST) ? fs.readFileSync(MANIFEST, "utf8") : "";
    if (current !== source) {
      console.error(`corpus: ${MANIFEST} is stale, run npm run corpus`);
      process.exit(1);
    }
    return;
  }
  fs.writeFileSync(MANIFEST, source);
  console.log(`corpus: ${MANIFEST} lists ${contentFiles().length} files`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) main();
